/**
 * 取按钮说明 过程函数
 * @param {string} action data-action
 * @param {{title: string, context: string}} zhEntry 中文条目（各页 infDict 里的那份）
 * @param {Object<string, string[]>} [overrideEn] 本页专属的英文条目（同一个工具在不同画板用法不同时用）
 * @returns {{title: string, context: string}|null}
 */
function tipOf(action, zhEntry, overrideEn) {
    if (!zhEntry) return null;
    if (currentLang() !== 'en') return zhEntry;
    const entry = (overrideEn && overrideEn[action]) || TIP_EN[action];
    return entry ? {title: entry[0], context: entry[1]} : zhEntry;
}

/** 当前语言 */
function currentLang() {
    const saved = localStorage.getItem('eurevival-lang');
    if (saved === 'zh' || saved === 'en') return saved;
    return /^zh/i.test(navigator.language || '') ? 'zh' : 'en';
}

/**
 * 非中文界面在文案换完之前先把页面藏起来，避免先闪一下中文
 * i18n.js 在 <head> 里同步执行，挂 class 的时机早于 body 渲染；
 * 各页脚本调用 applyI18n() 时摘掉，万一某页没调用，DOMContentLoaded 兜底
 */
const I18N_PENDING_CLASS = 'i18n-pending';

/**
 * 取文案 过程函数
 * @param {string} key 文案键
 * @param {Object} [params] 需要替换的占位符，如 {count: 3} → {count}
 * @returns {string}
 */
function t(key, params) {
    const dict = I18N_DICT[currentLang()] || I18N_DICT.zh;
    let text = dict[key] || I18N_DICT.zh[key] || key;
    if (params) {
        Object.entries(params).forEach(([name, value]) => {
            text = text.split(`{${name}}`).join(String(value));
        });
    }
    return text;
}

/**
 * 刷新页面上的静态文案 过程函数
 * 元素上写 data-i18n="键"；带 data-i18n-placeholder 的用于 placeholder；
 * 带 data-i18n-title 的用于 title
 * @param {Element|Document} [root]
 */
function applyI18n(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(element => { element.textContent = t(element.dataset.i18n); });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(element => { element.placeholder = t(element.dataset.i18nPlaceholder); });
    scope.querySelectorAll('[data-i18n-title]').forEach(element => { element.title = t(element.dataset.i18nTitle); });
    document.documentElement.lang = currentLang() === 'zh' ? 'zh-CN' : 'en';
    document.documentElement.classList.remove(I18N_PENDING_CLASS);
}

/**
 * 切换语言 过程函数
 * @param {string} lang 'zh' | 'en'
 */
function setLang(lang) {
    localStorage.setItem('eurevival-lang', lang);
    location.reload();
}

// 载入即埋点（脚本在 <head> 里，早于 body 渲染）：英文界面先把页面藏起来
if (currentLang() !== 'zh') document.documentElement.classList.add(I18N_PENDING_CLASS);
document.addEventListener('DOMContentLoaded', () => applyI18n());
